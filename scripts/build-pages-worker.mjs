import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["cloudflare/worker.js"],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  write: false,
  banner: { js: "// Generated by npm run build:web. Edit cloudflare/worker.js or functions/api/iptv.js." }
});
const source = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (await readFile("_worker.js", "utf8") !== source) throw new Error("Pages Worker is stale. Run npm run build:web.");
} else {
  await writeFile("_worker.js", source);
}
